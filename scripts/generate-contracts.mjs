import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = ['event.schema.json', 'api.schema.json'];
const schemas = Object.fromEntries(await Promise.all(files.map(async (file) => [file, JSON.parse(await readFile(path.join(root, 'shared/schema', file), 'utf8'))])));

const supported = new Set(['$schema', '$id', '$defs', '$ref', 'title', 'description', 'type', 'enum', 'const', 'oneOf', 'anyOf', 'allOf', 'properties', 'required', 'additionalProperties', 'items', 'format', 'pattern', 'minimum', 'maxItems']);

export function type(schema, file) {
  for (const key of Object.keys(schema)) if (!supported.has(key)) throw new Error(`Unsupported schema keyword: ${key}`);
  if (schema.$ref) {
    const [target, fragment] = schema.$ref.split('#');
    const targetFile = target || file;
    const targetSchema = schemas[targetFile];
    if (!targetSchema) throw new Error(`Unknown schema reference: ${schema.$ref}`);
    if (!fragment) return targetSchema.title === 'RegenteEvent' ? 'AgentEvent' : targetSchema.title;
    const match = /^\/\$defs\/([^/]+)$/.exec(fragment);
    if (!match || !(match[1] in targetSchema.$defs)) throw new Error(`Unknown schema reference: ${schema.$ref}`);
    return match[1];
  }
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(JSON.stringify).join(' | ');
  for (const [key, separator] of [['oneOf', ' | '], ['anyOf', ' | '], ['allOf', ' & ']]) {
    if (schema[key]) return schema[key].map((part) => `(${type(part, file)})`).join(separator);
  }
  if (Array.isArray(schema.type)) return schema.type.map((t) => type({ ...schema, type: t }, file)).join(' | ');
  switch (schema.type) {
    case 'string': return 'string';
    case 'integer': case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `Array<${type(schema.items, file)}>`;
    case 'object': {
      const properties = Object.entries(schema.properties ?? {}).map(([name, value]) => `${JSON.stringify(name)}${(schema.required ?? []).includes(name) ? '' : '?'}: ${type(value, file)};`);
      if (schema.additionalProperties === true || schema.additionalProperties === undefined) properties.push('[key: string]: unknown;');
      else if (schema.additionalProperties && typeof schema.additionalProperties === 'object') properties.push(`[key: string]: ${type(schema.additionalProperties, file)};`);
      return `{ ${properties.join(' ')} }`;
    }
    case undefined: if (Object.keys(schema).length === 0) return 'unknown'; throw new Error('Schema has no supported type');
    default: throw new Error(`Unsupported schema type: ${schema.type}`);
  }
}

export function contractsMatch(current, expected) { return current === expected; }

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
const declarations = [`export type AgentEvent = ${type(schemas[files[0]], files[0])};`];
for (const file of files) for (const [name, schema] of Object.entries(schemas[file].$defs ?? {})) declarations.push(`export type ${name} = ${type(schema, file)};`);
const output = `// Generated by scripts/generate-contracts.mjs; do not edit.\n\n${declarations.join('\n\n')}\n`;
const outputArg = process.argv.indexOf('--output');
const destination = outputArg < 0 ? path.join(root, 'ui/src/api/contracts.generated.ts') : path.resolve(process.argv[outputArg + 1]);
if (process.argv.includes('--check')) {
  const current = await readFile(destination, 'utf8').catch(() => '');
  if (!contractsMatch(current, output)) { console.error('Generated contracts are out of date; run pnpm generate:types.'); process.exitCode = 1; }
} else await writeFile(destination, output);
}
